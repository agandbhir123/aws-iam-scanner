"""
Parse the IAM scanner JSON report and write:
  - A formatted Markdown summary to the GitHub Actions job summary page
  - Structured outputs (grade, score, counts) to GITHUB_OUTPUT

Usage:
  python scripts/summarize.py iam_scan_report.json
"""

import json
import os
import sys
from pathlib import Path


GRADE_EMOJI = {"A": "🟢", "B": "🟢", "C": "🟡", "D": "🟠", "F": "🔴"}
SEV_EMOJI   = {"HIGH": "🔴", "MEDIUM": "🟡", "LOW": "🔵"}


def main():
    if len(sys.argv) < 2:
        print("Usage: python scripts/summarize.py <report.json>", file=sys.stderr)
        sys.exit(1)

    report_path = Path(sys.argv[1])
    if not report_path.exists():
        print(f"Report not found: {report_path}", file=sys.stderr)
        sys.exit(1)

    report   = json.loads(report_path.read_text())
    grade    = report.get("grade", "?")
    score    = report.get("score", 0)
    account  = report.get("account_id", "unknown")
    summary  = report.get("summary", {})
    findings = report.get("findings", [])

    high   = summary.get("high", 0)
    medium = summary.get("medium", 0)
    low    = summary.get("low", 0)
    total  = summary.get("total", 0)

    emoji = GRADE_EMOJI.get(grade, "⚪")

    # ── GitHub step summary (Markdown) ────────────────────────────────────
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        high_findings = [f for f in findings if f["severity"] == "HIGH"]
        med_findings  = [f for f in findings if f["severity"] == "MEDIUM"]

        lines = [
            f"## {emoji} IAM Security Scan — Grade **{grade}** &nbsp; `score {score}`",
            f"> **Account:** `{account}`",
            "",
            "| Severity | Count |",
            "|:---|---:|",
            f"| 🔴 HIGH | **{high}** |",
            f"| 🟡 MEDIUM | {medium} |",
            f"| 🔵 LOW | {low} |",
            f"| **Total** | **{total}** |",
            "",
        ]

        if total == 0:
            lines.append("### ✅ No findings — your IAM config looks clean!")

        if high_findings:
            lines += [
                "### 🔴 HIGH — Immediate action required",
                "",
            ]
            for f in high_findings:
                lines += [
                    f"**{f['resource_type']}** &nbsp; `{f['resource_name']}`",
                    f"> {f['issues'][0]}",
                    f"> *Fix:* {f['remediation']}",
                    "",
                ]

        if med_findings:
            lines += [
                "### 🟡 MEDIUM — Should be addressed soon",
                "",
            ]
            for f in med_findings:
                lines += [
                    f"- **{f['resource_type']}** `{f['resource_name']}` — {f['issues'][0]}",
                ]
            lines.append("")

        lines += [
            "---",
            "_Generated by [IAM Scanner](https://github.com). "
            "Download the full JSON report from the Artifacts section above._",
        ]

        with open(summary_path, "w") as fh:
            fh.write("\n".join(lines) + "\n")

    # ── GitHub outputs ────────────────────────────────────────────────────
    outputs_path = os.environ.get("GITHUB_OUTPUT")
    if outputs_path:
        with open(outputs_path, "a") as fh:
            fh.write(f"grade={grade}\n")
            fh.write(f"score={score}\n")
            fh.write(f"high_count={high}\n")
            fh.write(f"medium_count={medium}\n")
            fh.write(f"low_count={low}\n")
            fh.write(f"total={total}\n")

    # ── Console output (always) ───────────────────────────────────────────
    print(f"Grade: {grade}  Score: {score}")
    print(f"Findings: {high} HIGH  {medium} MEDIUM  {low} LOW  ({total} total)")

    if high > 0:
        print(f"\nHIGH findings:")
        for f in findings:
            if f["severity"] == "HIGH":
                print(f"  [{f['resource_type']}] {f['resource_name']}: {f['issues'][0]}")


if __name__ == "__main__":
    main()
